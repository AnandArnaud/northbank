-- Snowflake. Product events from the app land here (loaded nightly from the app's event spool).
CREATE DATABASE IF NOT EXISTS PRODUCT;
CREATE SCHEMA IF NOT EXISTS PRODUCT.ANALYTICS;

CREATE TABLE IF NOT EXISTS PRODUCT.ANALYTICS.EVENTS (
  EVENT_ID      STRING DEFAULT UUID_STRING(),
  EVENT_NAME    STRING NOT NULL,
  USER_ID       STRING,
  ANONYMOUS_ID  STRING NOT NULL,
  PROPERTIES    VARIANT,
  EVENT_TIME    TIMESTAMP_NTZ NOT NULL,
  LOADED_AT     TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS PRODUCT.ANALYTICS.USERS (
  USER_ID       STRING NOT NULL,
  EMAIL         STRING,
  PLAN          STRING,
  SIGNED_UP_AT  TIMESTAMP_NTZ,
  PRIMARY KEY (USER_ID)
);

-- Daily active users, used by the ops dashboard.
CREATE OR REPLACE VIEW PRODUCT.ANALYTICS.DAILY_ACTIVE_USERS AS
SELECT DATE_TRUNC('day', EVENT_TIME) AS DAY, COUNT(DISTINCT COALESCE(USER_ID, ANONYMOUS_ID)) AS ACTIVE_USERS
FROM PRODUCT.ANALYTICS.EVENTS
GROUP BY 1;
